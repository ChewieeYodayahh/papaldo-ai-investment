#!/usr/bin/env node
/**
 * Rebuild AGENTS.md from CLAUDE.md plus every `.claude/rules/*.md`.
 *
 * Claude Code loads the short CLAUDE.md every session and each rule file only
 * when it touches matching paths, which keeps sessions cheap. Other agents
 * (Codex, Gemini, …) read AGENTS.md alone and never see `.claude/rules/`, so
 * they get everything in one file. Run after editing either source:
 *
 *   npm run agents:sync          write AGENTS.md
 *   npm run agents:sync -- --check   exit 1 if AGENTS.md is out of date
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import path from 'node:path'

const RULES = '.claude/rules'

function splitFrontmatter(text) {
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/)
  if (!match) return { paths: [], body: text }
  const paths = [...match[1].matchAll(/^\s*-\s*"?([^"\n]+)"?\s*$/gm)].map((m) => m[1])
  return { paths, body: text.slice(match[0].length) }
}

const core = readFileSync('CLAUDE.md', 'utf8').trimEnd()
const rules = readdirSync(RULES)
  .filter((f) => f.endsWith('.md'))
  .sort()
  .map((file) => {
    const { paths, body } = splitFrontmatter(readFileSync(path.join(RULES, file), 'utf8'))
    const scope = paths.length ? `_Applies when working in: ${paths.map((p) => `\`${p}\``).join(', ')}_\n\n` : ''
    // Demote the rule's own H1 so it nests under "Path-scoped rules".
    return body.trim().replace(/^# /, '### ').replace(/\n# /g, '\n### ').replace(/^(### .*)$/m, `$1\n\n${scope}`.trimEnd())
  })

const note = `## A note for non-Claude agents reading this file

This file is generated by \`npm run agents:sync\` from \`CLAUDE.md\` and
\`.claude/rules/*.md\` — edit those, not this. Claude Code loads the rules only
when it touches matching paths; they are inlined here because other agents do
not read \`.claude/\`. The AI service lives in \`core/services/claude.ts\`
(it currently calls Gemini); whatever agent you are, describe the codebase as
it actually is — this file and \`CLAUDE.md\` always say the same thing about the
code, even where their framing differs.`

const output = `${core}\n\n## Path-scoped rules\n\n${rules.join('\n\n')}\n\n${note}\n`

if (process.argv.includes('--check')) {
  const current = existsSync('AGENTS.md') ? readFileSync('AGENTS.md', 'utf8') : ''
  if (current !== output) {
    console.error('AGENTS.md is out of date. Run: npm run agents:sync')
    process.exit(1)
  }
  console.log('AGENTS.md is current.')
} else {
  writeFileSync('AGENTS.md', output)
  console.log(`AGENTS.md written (${output.split('\n').length} lines: CLAUDE.md + ${rules.length} rule files).`)
}
